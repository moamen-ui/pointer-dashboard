// Formats a user's request datetime as dd-MM-yyyy HH:mm (24h, zero-padded),
// falling back to an em dash when the value is missing or invalid.
export function formatRequestedAt(value: string | null | undefined): string {
  if (!value) return '—';
  const d = new Date(value);
  if (Number.isNaN(d.getTime())) return '—';
  const p = (n: number) => String(n).padStart(2, '0');
  return `${p(d.getDate())}-${p(d.getMonth() + 1)}-${d.getFullYear()} ${p(d.getHours())}:${p(d.getMinutes())}`;
}
